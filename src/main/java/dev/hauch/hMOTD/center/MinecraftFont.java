    /**
     * Returns the horizontal advance of the given code point.
     *
     * @param codePoint the unicode code point
     * @param bold     whether the glyph is rendered bold
     * @return the advance in pixels
     */
    public static float advance(int codePoint, boolean bold) {
        if (codePoint < 0 || codePoint >= TABLE_SIZE) {
            return bold ? DEFAULT_ADVANCE_BOLD : DEFAULT_ADVANCE;
        }
        float value = bold ? ADVANCE_BOLD[codePoint] : ADVANCE[codePoint];
        if (value < 0.0F) {
            return bold ? DEFAULT_ADVANCE_BOLD : DEFAULT_ADVANCE;
        }
        return value;
    }

    public static float advance(char character, boolean bold) {
        return advance((int) character, bold);
    }
