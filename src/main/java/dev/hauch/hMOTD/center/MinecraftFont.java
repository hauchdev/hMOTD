        int index = 0;
        while (index < DATA.length()) {
            int end = DATA.indexOf(';', index);
            if (end < 0) {
                end = DATA.length();
            }
            String entry = DATA.substring(index, end);
            index = end + 1;
            if (entry.isEmpty()) {
                continue;
            }
            int first = entry.indexOf(':');
            int second = entry.indexOf(':', first + 1);
            int codePoint = Integer.parseInt(entry.substring(0, first));
            if (codePoint < 0 || codePoint >= TABLE_SIZE) {
                continue;
            }
            ADVANCE[codePoint] = Integer.parseInt(entry.substring(first + 1, second)) / 2.0F;
            ADVANCE_BOLD[codePoint] = Integer.parseInt(entry.substring(second + 1)) / 2.0F;
        }
